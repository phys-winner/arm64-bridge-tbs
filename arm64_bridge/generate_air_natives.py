"""Generate typed AIR JNI wrappers from canonical smali. Check with --check."""
import argparse
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
TYPES = dict(zip("VZBCSIJFD", ["void", "jboolean", "jbyte", "jchar", "jshort", "jint", "jlong", "jfloat", "jdouble"]))


def descriptor(value):
    tokens = re.findall(r"\[*L[^;]+;|\[*[ZBCSIJFDV]", value)
    if "".join(tokens) != value or any(t.lstrip("[") == "V" for t in tokens):
        raise ValueError("Invalid JNI parameter descriptor: " + value)
    return tokens


def ctype(token):
    if token == "Ljava/lang/String;":
        return "jstring"
    if token.startswith("["):
        return TYPES[token[1:]] + "Array" if token[1:] in TYPES else "jobjectArray"
    return "jobject" if token.startswith("L") else TYPES[token]


def mangle(text):
    return "".join({"/": "_", "_": "_1", ";": "_2", "[": "_3"}.get(c, c if c.isascii() and c.isalnum() else "_0%04x" % ord(c)) for c in text)


def native_owners(directory):
    owners = {}
    for path in sorted(directory.rglob("*.smali")):
        text = path.read_text(encoding="utf8")
        if " native " not in text:
            continue
        owner = re.search(r"^\.class[^\n]* (L[^;]+;)$", text, re.M)[1]
        found = []
        for flags, name, args, result in re.findall(r"^\.method ((?:\S+ )*)([^\s(]+)\(([^)]*)\)(\S+)$", text, re.M):
            if "native" in flags.split():
                found.append({"owner": owner, "method_descriptor": name + "(" + args + ")" + result, "static": "static" in flags.split()})
        if found:
            owners[owner] = found
    return owners


def generate(original_directory=ROOT / "decoded_original/smali", current_directory=ROOT / "app/smali"):
    original = native_owners(original_directory)
    current = native_owners(current_directory)
    del current["Lcom/stoicstudio/port/Arm64Bridge;"]
    if current.keys() != original.keys():
        raise ValueError("Original AIR native owner set changed")
    owners = []
    for owner, expected in original.items():
        found = current[owner]
        if found != expected:
            raise ValueError("Native declarations changed: " + owner)
        owners.append((owner[1:-1], found))
    lines = ["// Generated by generate_air_natives.py; do not edit.", "const NativeBinding kBindings[] = {"]
    methods = []
    for owner, rows in owners:
        for m in rows:
            name, args, ret = re.fullmatch(r"([^\s(]+)\(([^)]*)\)(\S+)", m["method_descriptor"]).groups()
            signature = "(" + args + ")" + ret
            overload = sum(x["method_descriptor"].split("(")[0] == name for x in rows) > 1
            symbol = "Java_" + mangle(owner) + "_" + mangle(name) + ("__" + mangle(args) if overload else "")
            lines.append("    {%s, %s, %s, %s, %s}," % tuple([json.dumps(owner), json.dumps(name), json.dumps(signature), str(m["static"]).lower(), json.dumps(symbol)]))
            methods.append((owner, name, signature, [ctype(ret), *map(ctype, descriptor(args))]))
    assert len(methods) == 132 and len(owners) == 29
    lines.append("};")
    start = 0
    for group, (owner, rows) in enumerate(owners):
        lines.append("static const JNINativeMethod kMethods%d[] = {" % group)
        for i in range(start, start + len(rows)):
            _, name, sig, types = methods[i]
            lines.append('    {const_cast<char*>(%s), const_cast<char*>(%s), reinterpret_cast<void*>(Forward<%s>)},' % (json.dumps(name), json.dumps(sig), ", ".join([str(i), *types])))
        lines.append("};")
        start += len(rows)
    lines.append("static const NativeClass kClasses[] = {")
    for group, (owner, _) in enumerate(owners):
        lines.append("    {%s, kMethods%d, sizeof(kMethods%d) / sizeof(JNINativeMethod)}," % (json.dumps(owner), group, group))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--original", type=Path, default=ROOT / "decoded_original/smali")
    parser.add_argument("--current", type=Path, default=ROOT / "app/smali")
    args = parser.parse_args()
    assert descriptor("IFFFIFFZ[FI") == ["I", "F", "F", "F", "I", "F", "F", "Z", "[F", "I"]
    assert ctype("[F") == "jfloatArray" and ctype("[[I") == "jobjectArray"
    assert mangle("com/foo/A_b") == "com_foo_A_1b"
    content = generate(args.original, args.current)
    target = HERE / "src/air_natives.inc"
    if args.check:
        assert target.read_text(encoding="utf8") == content
    else:
        target.write_text(content, encoding="utf8")
    print("AIR_NATIVE_DECLARATIONS_PASS classes=29 methods=132 softfp=true package_private_included=true")


if __name__ == "__main__":
    main()
